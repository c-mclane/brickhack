/* hack.c test_move: 1 = allow, 0 = refuse, -1 = normal NetHack rules */
int
web_test_move(int x, int y, int mode)
{
    if (!isok(x, y))
        return -1;
    if (x == web_ok_x && y == web_ok_y) {
        if (mode == DO_MOVE)
            web_ok_x = web_ok_y = -1;
        return 1; /* the client climbed onto blocks / a wall here */
    }
    if (web_blocks[y][x])
        return 0; /* runs and travel never walk into blocks */
    return -1;
}

