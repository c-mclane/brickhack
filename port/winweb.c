static void
block_cmd(int c)
{
    int x, y, n;
    switch (c) {
    case 'B':
        if (inbuf[1] == 'C')
            memset(web_blocks, 0, sizeof web_blocks);
        else if (sscanf(inbuf + 1, "%d %d %d", &x, &y, &n) == 3 && isok(x, y))
            web_blocks[y][x] = (unsigned char) (n > 0);
        break;
    case 'A':
        if (sscanf(inbuf + 1, "%d %d", &x, &y) == 2)
            web_ok_x = x, web_ok_y = y;
        break;
    case 'Z':
        if (sscanf(inbuf + 1, "%d", &n) == 1) {
            web_hero_z = n;
            /* landed on the ground somewhere that isn't floor (fell off a
               wall or block tower into solid rock): put the hero back */
            if (n == 0 && program_state.in_moveloop && isok(u.ux, u.uy)
                && (IS_ROCK(levl[u.ux][u.uy].typ)
                    || closed_door(u.ux, u.uy))) {
                coord cc;
                if (enexto(&cc, u.ux, u.uy, youmonst.data)) {
                    You("tumble back into the dungeon!");
                    teleds(cc.x, cc.y, FALSE);
                    sync_all();
                }
            }
        }
        break;
    case 'P': /* stepped into one of Dreamland's portals: up to the next level
                 (level 1: on top of the tower; the glade: among the standing
                 stones; the sky platform: once the Waddle Dees are gone; the
                 Kirby field: hidden inside a checkered tower; the palace: in a
                 hedge maze, after an offering) */
        if (program_state.in_moveloop
            && ((flags.dreamland && u.uz.dnum == 0 && u.uz.dlevel == 1
                 && u.ux == DREAM_PORTAL_X && u.uy == DREAM_PORTAL_Y && web_hero_z >= DREAM_PORTAL_Z)
                || (web_portal2_open() && u.ux == DREAM_SKY_PORTAL_X && u.uy == DREAM_SKY_PORTAL_Y)
                || (flags.dreamland && u.uz.dnum == 0 && u.uz.dlevel == DREAM_LV_GLADE
                    && u.ux == DREAM_GLADE_PORTAL_X && u.uy == DREAM_GLADE_PORTAL_Y)
                || (flags.dreamland && u.uz.dnum == 0 && u.uz.dlevel == DREAM_LV_KIRBY
                    && u.ux == DREAM_KIRBY_PORTAL_X && u.uy == DREAM_KIRBY_PORTAL_Y)
                || web_portal4_here() || web_portal5_here())) {
            d_level up;
            up.dnum = u.uz.dnum;
            up.dlevel = u.uz.dlevel + 1;
            schedule_goto(&up, FALSE, FALSE, 0, "You step into the shimmering portal...",
                          "You arrive higher up in Dreamland.");
        }
        break;
    case 'F': /* fell off one of Dreamland's floating platforms: back on it */
        if (program_state.in_moveloop && flags.dreamland && u.uz.dnum == 0 && u.uz.dlevel >= 2
            && IS_AIR(levl[u.ux][u.uy].typ)) {
            static const char *saved[] = {
                "You tumble off the edge of the world... and a passing star scoops you back up!",
                "Whoops! A gust of wind tosses you back onto the platform. Gravity is optional here.",
                "You fall, and fall... and wake up back on the platform. A dream within a dream?",
                "A flock of puffy clouds catches you and bounces you right back. How embarrassing.",
                "You plummet into the sky! The sky politely returns you.",
                "Down you go... boing! Dreamland doesn't let anyone fall out of it.",
            };
            int tries;
            for (tries = 0; tries < 500; tries++) {
                x = rn1(COLNO - 3, 2);
                y = rn2(ROWNO);
                if (isok(x, y) && levl[x][y].typ == ROOM && !web_blocks[y][x] && !MON_AT(x, y))
                    break;
            }
            if (tries < 500) {
                pline("%s", saved[rn2(SIZE(saved))]);
                teleds(x, y, FALSE);
                sync_all();
            }
        }
        break;
    case 'W': /* give: "W<hex item name>", made the way a wish is */
        if (program_state.in_moveloop) {
            char what[BUFSZ];
            struct obj *otmp;
            int len = unhex(inbuf + 1);
            if (len >= BUFSZ)
                len = BUFSZ - 1;
            memcpy(what, inbuf + 1, len);
            what[len] = '\0';
            {   /* an artifact by its name (even one never found in the dungeon,
                   which a wish can't give: the golden weapons of Spinjitzu) */
                short otyp;
                const char *an = artifact_name(what, &otyp);
                otmp = an ? oname(mksobj(otyp, TRUE, FALSE), an)
                          : readobjnam(what, (struct obj *) 0, TRUE);
            }
            if (!otmp)
                pline("Nothing fitting \"%s\" exists.", what);
            else
                web_give(otmp);
            sync_all();
        }
        break;
    case 'V': /* dev cheese: Grayswandir and the Blazing Cheese armour */
        if (program_state.in_moveloop) {
            struct obj *otmp = mksobj(SILVER_SABER, FALSE, FALSE);
            otmp = oname(otmp, artiname(ART_GRAYSWANDIR));
            bless(otmp);
            otmp->spe = 7;
            otmp->oerodeproof = 1;
            web_give(otmp);
            otmp = mksobj(RED_DRAGON_SCALE_MAIL, FALSE, FALSE);
            otmp = oname(otmp, "Blazing Cheese");
            bless(otmp);
            otmp->spe = 3;
            web_give(otmp);
            pline("Dev cheese! Wear the Blazing Cheese and anything that hits you catches fire.");
            sync_all();
        }
        break;
    case 'T': /* dev tp: "T<n>", to level n of the dungeon you're in (at the
                 end of the turn: the client follows it with a turn's wait) */
        if (sscanf(inbuf + 1, "%d", &n) == 1 && program_state.in_moveloop) {
            int bottom = dunlevs_in_dungeon(&u.uz);
            if (n < 1 || n > bottom)
                pline("Dev tp: there's no level %d here (1 to %d).", n, bottom);
            else if (n == u.uz.dlevel)
                pline("Dev tp: you're already on level %d.", n);
            else {
                d_level to;
                to.dnum = u.uz.dnum;
                to.dlevel = n;
                schedule_goto(&to, FALSE, FALSE, 0, "Dev tp! The world spins away...", (char *) 0);
            }
        }
        break;
    case 'D':
        if (sscanf(inbuf + 1, "%d", &n) == 1 && n > 0 && program_state.in_moveloop) {
            You("hit the ground hard!");
            losehp(n, "fall", KILLED_BY_AN);
            sync_all();
        }
        break;
    }
}

/* read one line of input; K lines are always absorbed into the key queue.
 * Returns the first character of the line ('K', 'C', 'M', 'L', 'E', 'X'). */
static int
read_cmd(void)
{
    size_t n;

    if (!fgets(inbuf, sizeof inbuf, stdin)) {
        /* client went away: save and quit */
        end_of_input();
        nh_terminate(EXIT_SUCCESS);
    }
    n = strlen(inbuf);
    while (n && (inbuf[n - 1] == '\n' || inbuf[n - 1] == '\r'))
        inbuf[--n] = '\0';
    if (inbuf[0] == 'K') {
        int i, len = unhex(inbuf + 1);
        for (i = 0; i < len; i++)
            kq_push((unsigned char) inbuf[1 + i]);
    } else if (index("BAZDPFWVT", inbuf[0])) {
        block_cmd(inbuf[0]);
    }
    return inbuf[0];
}

