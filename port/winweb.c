static FILE *out;

static void
jstr(const char *s)
{
    fputc('"', out);
    for (; s && *s; s++) {
        unsigned char c = (unsigned char) *s;
        if (c == '"' || c == '\\')
            fprintf(out, "\\%c", c);
        else if (c < 0x20 || c >= 0x7f)
            fprintf(out, "\\u%04x", c);
        else
            fputc(c, out);
    }
    fputc('"', out);
}

static void
endmsg(void)
{
    fputs("}\n", out);
    fflush(out);
}

