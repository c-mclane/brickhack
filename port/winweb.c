/* a FILE that writes into a malloc'd buffer (*bufp, *lenp: set by
   web_mem_close): open_memstream where there is one; on Windows a scratch
   file in the game's folder, read back when it's closed */
#ifdef _WIN32
static FILE *
web_mem_open(char **bufp, size_t *lenp)
{
    *bufp = 0;
    *lenp = 0;
    return fopen("web-snapshot.tmp", "w+b");
}

static void
web_mem_close(FILE *f, char **bufp, size_t *lenp)
{
    long n;
    fflush(f);
    n = ftell(f);
    *bufp = malloc(n + 1);
    rewind(f);
    *lenp = fread(*bufp, 1, n, f);
    (*bufp)[*lenp] = '\0';
    fclose(f);
}
#else
#define web_mem_open(bufp, lenp) open_memstream(bufp, lenp)
#define web_mem_close(f, bufp, lenp) fclose(f)
#endif

/* build into a malloc'd buffer (web_mem_open) so we can diff */
