/* Dreamland's Fountain of Dreams: the trial.  Kirby (placed by
   the level); when he falls, a pause, maybe some food, then two Waddle Doos;
   then a cherub; then Kirby again; then a portal opens on the island.  The
   wave is kept in the spare flags of an air square in the corner (saved with
   the level).  Called once a turn (allmain.c). */
#define DREAM_FTN_WAVE levl[DREAM_FTN_FLAG_X][DREAM_FTN_FLAG_Y].flags
#define DREAM_FTN_DONE 7
static int
web_alive(const char *name)
{
    struct monst *m;
    int n = 0;
    for (m = fmon; m; m = m->nmon)
        if (!DEADMONSTER(m) && !strcmp(m->data->mname, name))
            n++;
    return n;
}
static void
web_wave_spawn(const char *name, int n)
{
    int pm = name_to_mon(name), i;
    coord cc;
    struct monst *mtmp;
    if (pm < LOW_PM)
        return;
    for (i = 0; i < n; i++)
        if (enexto(&cc, DREAM_FTN_SPAWN_X + (n > 1 ? 2 * i - 1 : 0), DREAM_FTN_SPAWN_Y, &mons[pm])
            && (mtmp = makemon(&mons[pm], cc.x, cc.y, NO_MM_FLAGS)) != 0) {
            mtmp->mpeaceful = 0; /* it's a trial: everything comes to fight */
            set_malign(mtmp);
        }
}
static void
web_wave_food(void)
{
    static const int food[] = { MELON, APPLE, ORANGE, BANANA, PEAR, CREAM_PIE, CANDY_BAR, PANCAKE };
    int n = 2 + rn2(3), tries;
    for (tries = 0; n > 0 && tries < 400; tries++) {
        int x = DREAM_FTN_CX - DREAM_FTN_R + rn2(2 * DREAM_FTN_R + 1), y = DREAM_FTN_CY - DREAM_FTN_R + rn2(2 * DREAM_FTN_R + 1);
        if (!isok(x, y) || levl[x][y].typ != ROOM || web_blocks[y][x] || (x == u.ux && y == u.uy))
            continue;
        (void) mksobj_at(food[rn2(SIZE(food))], x, y, TRUE, FALSE);
        newsym(x, y);
        n--;
    }
}
void
web_dream_waves(void)
{
    int wave;
    if (!flags.dreamland || u.uz.dnum != 0 || u.uz.dlevel != DREAM_LV_FOUNTAIN)
        return;
    wave = DREAM_FTN_WAVE;
    switch (wave) {
    case 0: /* Kirby */
    case 2: /* the Waddle Doos */
    case 4: /* the cherub */
    case 6: /* Kirby, again */
        if (web_alive(wave == 2 ? "Waddle Doo" : wave == 4 ? "cherub" : "Kirby"))
            return;
        wave++;
        if (wave == 1) {
            /* the Star Rod pops off the top of the fountain: yours to take */
            struct obj *rod = mksobj(WAN_STRIKING, FALSE, FALSE);
            rod = oname(rod, "Star Rod");
            bless(rod);
            rod->spe = 5;
            rod->recharged = 0;
            place_object(rod, DREAM_FTN_ROD_X, DREAM_FTN_ROD_Y);
            stackobj(rod);
            newsym(DREAM_FTN_ROD_X, DREAM_FTN_ROD_Y);
            pline("Kirby is defeated!  The fountain falls quiet... but the trial isn't over.");
            pline("With a *pop*, the Star Rod flies off the top of the fountain and lands on the grass!");
        }
        else if (wave == DREAM_FTN_DONE) {
            pline("Kirby is defeated, again!  The Star Rod blazes with light.");
            pline("Somewhere on the island, a portal shimmers open...");
        } else
            pline("The fountain falls quiet...");
        break;
    case 1:
    case 3:
    case 5: /* a pause before the next wave */
        if (rn2(6))
            return;
        if (wave == 1) {
            if (rn2(10) < 7) {
                web_wave_food();
                pline("Food tumbles down out of the stars onto the grass!");
            }
            pline("Two Waddle Doos float up over the edge of the island!");
            web_wave_spawn("Waddle Doo", 2);
        } else if (wave == 3) {
            pline("A cherub descends from the stars!");
            web_wave_spawn("cherub", 1);
        } else {
            pline("Kirby is back, and he looks angry!");
            web_wave_spawn("Kirby", 1);
        }
        wave++;
        break;
    default:
        return;
    }
    DREAM_FTN_WAVE = wave;
    sync_all();
}
/* zap.c weffects: the Star Rod (a wand named so) fires a beam of stars that
   obliterates every monster in its path, leaving nothing behind; 1 = it was
   the Star Rod (and the zap is done) */
int
web_star_rod(struct obj *obj)
{
    struct monst *mtmp;
    int x = u.ux, y = u.uy, range = 13;
    if (obj->oclass != WAND_CLASS || !obj->onamelth || strcmp(ONAME(obj), "Star Rod"))
        return 0;
    if (u.uswallow) {
        mtmp = u.ustuck;
        pline("Stars burst out of %s!", mon_nam(mtmp));
        expels(mtmp, mtmp->data, FALSE);
        pline("%s is obliterated!", Monnam(mtmp));
        xkilled(mtmp, 2);
        return 1;
    }
    if (u.dz) {
        pline("Stars scatter %s, twinkling harmlessly.", u.dz > 0 ? "across the ground" : "into the sky");
        return 1;
    }
    pline("A beam of stars bursts from the Star Rod!");
    tmp_at(DISP_BEAM, zapdir_to_glyph(u.dx, u.dy, 5));
    while (range-- > 0) {
        x += u.dx;
        y += u.dy;
        if (!isok(x, y) || !ZAP_POS(levl[x][y].typ) || closed_door(x, y))
            break;
        tmp_at(x, y);
        delay_output();
        if ((mtmp = m_at(x, y)) != 0) {
            if (canspotmon(mtmp))
                pline("%s is obliterated!", Monnam(mtmp));
            else
                pline("Something is obliterated!");
            mtmp->mhp = 0;
            xkilled(mtmp, 2); /* (nothing left behind) */
        }
    }
    tmp_at(DISP_END, 0);
    return 1;
}

