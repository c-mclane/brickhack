static int
web_nhgetch(void)
{
    while (kq_empty()) {
        request_key(0);
        while (read_cmd() != 'K')
            ;
    }
    return kq_pop();
}

static int
web_nh_poskey(int *x, int *y, int *mod)
{
    while (kq_empty()) {
        int c;
        request_key(1);
        for (;;) {
            c = read_cmd();
            if (c == 'K')
                break;
            if (c == 'C') {
                int cx, cy, b;
                if (sscanf(inbuf + 1, "%d %d %d", &cx, &cy, &b) == 3
                    && isok(cx, cy)) {
                    *x = cx;
                    *y = cy;
                    *mod = b == 2 ? CLICK_2 : CLICK_1;
                    return 0;
                }
            }
        }
    }
    return kq_pop();
}

