/* kind codes sent to the client */
static char
glyph_kind(int glyph)
{
    if (glyph == NO_GLYPH)
        return ' ';
    if (glyph_is_invisible(glyph))
        return 'i';
    if (glyph >= GLYPH_PET_OFF && glyph < GLYPH_INVIS_OFF)
        return 'p';
    if (glyph_is_monster(glyph))
        return 'm';
    if (glyph_is_statue(glyph))
        return 's';
    if (glyph_is_object(glyph) && !glyph_is_body(glyph)) {
        int otyp = glyph_to_obj(glyph);
        if (otyp == CHEST || otyp == LARGE_BOX || otyp == ICE_BOX)
            return 'C'; /* drawn as a Minecraft-style chest block */
    }
    if (glyph_is_body(glyph) || glyph_is_object(glyph))
        return 'o';
    if (glyph_is_cmap(glyph)) {
        int c = glyph_to_cmap(glyph);
        if (c >= S_vbeam)
            return 'e'; /* beams, sparkles, swallow parts, ... */
        if (c >= S_arrow_trap)
            return 't';
        return 'c';
    }
    if (glyph_is_swallow(glyph))
        return 'w';
    if (glyph_is_warning(glyph))
        return 'W';
    if (glyph >= GLYPH_ZAP_OFF && glyph < GLYPH_SWALLOW_OFF)
        return 'z';
    if (glyph >= GLYPH_EXPLODE_OFF && glyph < GLYPH_ZAP_OFF)
        return 'x';
    return '?';
}

static int
glyph_cmapidx(int glyph)
{
    if (glyph != NO_GLYPH && glyph_is_cmap(glyph))
        return glyph_to_cmap(glyph);
    return -1;
}

static int
tile_of(int glyph)
{
    if (glyph == NO_GLYPH || glyph < 0 || glyph >= MAX_GLYPH)
        return -1;
    return glyph2tile[glyph];
}

static void
reset_map(void)
{
    int x, y;
    for (y = 0; y < ROWNO; y++)
        for (x = 0; x < COLNO; x++) {
            mapglyph_buf[y][x] = cmap_to_glyph(S_stone);
            mapbk_buf[y][x] = NO_GLYPH;
            map_dirty[y][x] = FALSE;
            last_pile[y][x] = 0;
        }
    map_cleared = TRUE;
    last_vis[0] = '\0';
    last_lit[0] = '\0';
}

static void
flush_map(void)
{
    int x, y, n = 0;

    if (map_cleared) {
        fputs("{\"t\":\"clear\"", out);
        endmsg();
        map_cleared = FALSE;
    }
    for (y = 0; y < ROWNO; y++)
        for (x = 0; x < COLNO; x++) {
            int g, bk;
            if (!map_dirty[y][x])
                continue;
            map_dirty[y][x] = FALSE;
            g = mapglyph_buf[y][x];
            bk = mapbk_buf[y][x];
            fputs(n ? "," : "{\"t\":\"map\",\"c\":[", out);
            /* [x, y, tile, kind, cmap, bktile, bkcmap, altar, high] (altar: an
               altar there, its alignment: -1 chaotic, 0 neutral, 1 lawful, -128
               unaligned; or 2, none: the client builds it in brick, coloured;
               high: 1, a high altar, the Astral Plane's or the Sanctum's) */
            fprintf(out, "[%d,%d,%d,\"%c\",%d,%d,%d,%d,%d]", x, y,
                    glyph_is_body(g) && !Hallucination ? CORPSE_TILE + tile_of(monnum_to_glyph(g - GLYPH_BODY_OFF)) : tile_of(g), /* (a corpse: whose, web_obj_tile) */
                    glyph_kind(g), glyph_cmapidx(g), tile_of(bk),
                    glyph_cmapidx(bk),
                    IS_ALTAR(levl[x][y].typ) ? (int) Amask2align(levl[x][y].altarmask & AM_MASK) : 2,
                    IS_ALTAR(levl[x][y].typ) && (levl[x][y].altarmask & AM_SHRINE)
                        && (Is_astralevel(&u.uz) || Is_sanctum(&u.uz)) ? 1 : 0);
            n++;
        }
    if (n) {
        fputc(']', out);
        endmsg();
    }
}

static void
flush_vis(void)
{
    char vis[ROWNO * COLNO + 1], lit[ROWNO * COLNO + 1];
    int x, y;

    if (!program_state.in_moveloop)
        return;
    /* (and which squares are a room's floor, lit ('l') or dark ('d'): a dark room drawn dark, but for your light; a wand of
       light, or a spell, lights it: litroom) */
    for (y = 0; y < ROWNO; y++)
        for (x = 0; x < COLNO; x++) {
            vis[y * COLNO + x] = (x > 0 && cansee(x, y)) ? '1' : '0';
            lit[y * COLNO + x] = x > 0 && IS_ROOM(levl[x][y].typ) ? (levl[x][y].lit ? 'l' : 'd') : '0';
        }
    vis[ROWNO * COLNO] = lit[ROWNO * COLNO] = '\0';
    if (strcmp(vis, last_vis) || strcmp(lit, last_lit)) {
        Strcpy(last_vis, vis);
        Strcpy(last_lit, lit);
        fprintf(out, "{\"t\":\"vis\",\"w\":%d,\"h\":%d,\"v\":\"%s\",\"l\":\"%s\"", COLNO,
                ROWNO, vis, lit);
        endmsg();
    }
}

/* Piles: the map shows only the top object of a pile, but the client lays
 * every item there on the floor (as brick). For each square in sight (yours
 * too), the tiles of the objects on it, top first, when that changes:
 *   {"t":"piles","p":[[x, y, [tile, ...]], ...]}  ([] : nothing there now) */
#define PILE_MAX 12
static void
flush_piles(void)
{
    int x, y, n = 0;

    if (!program_state.in_moveloop)
        return;
    for (y = 0; y < ROWNO; y++)
        for (x = 1; x < COLNO; x++) {
            struct obj *o;
            int tiles[PILE_MAX], k = 0, i;
            unsigned long sig = 1;

            if (!cansee(x, y) && !(x == u.ux && y == u.uy))
                continue;
            for (o = level.objects[x][y]; o && k < PILE_MAX; o = o->nexthere) {
                tiles[k] = web_obj_tile(o, obj_to_glyph(o));
                sig = sig * 1000003UL + (unsigned long) (tiles[k] + 7);
                k++;
            }
            if (sig == last_pile[y][x] || (k == 0 && last_pile[y][x] == 0))
                continue;
            last_pile[y][x] = k ? sig : 0;
            fputs(n ? "," : "{\"t\":\"piles\",\"p\":[", out);
            fprintf(out, "[%d,%d,[", x, y);
            for (i = 0; i < k; i++)
                fprintf(out, i ? ",%d" : "%d", tiles[i]);
            fputs("]]", out);
            n++;
        }
    if (n) {
        fputc(']', out);
        endmsg();
    }
}

