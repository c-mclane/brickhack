static void
flush_snap(char **last, char *now)
{
    if (!*last || strcmp(*last, now)) {
        fputs(now, out);
        endmsg();
        free(*last);
        *last = now;
    } else
        free(now);
}

/* send everything the client needs before we block for input */
static void
sync_all(void)
{
    flush_map();
    if (program_state.in_moveloop && !program_state.gameover) {
        int lk = ledger_no(&u.uz);
        if (lk != last_level_key) {
            last_level_key = lk;
            fprintf(out, "{\"t\":\"level\",\"depth\":%d,\"dname\":",
                    depth(&u.uz));
            jstr(web_dname());
            if (Is_stronghold(&u.uz)) { /* the Castle: where its walls stand, so the client can raise them into a real castle */
                /* (dat/castle.des: its map is 63x17, the drawbridge's span at (5,8), its walls from (1,1) to (61,15)) */
                int x, y;
                for (y = 0; y < ROWNO; y++)
                    for (x = 1; x < COLNO; x++)
                        if (levl[x][y].typ == DRAWBRIDGE_UP || levl[x][y].typ == DRAWBRIDGE_DOWN) {
                            fprintf(out, ",\"castle\":[%d,%d,%d,%d]", x - 4, y - 7, x + 56, y + 7);
                            x = COLNO, y = ROWNO;
                        }
            }
            endmsg();
        }
        flush_vis();
        flush_piles();
        flush_snap(&last_stat, build_status());
        flush_snap(&last_inv, build_inventory());
        flush_snap(&last_mons, build_monsters());
    }
    fflush(out);
}

