static void
web_add_menu(winid id, int glyph, const ANY_P *identifier, CHAR_P ch,
             CHAR_P gch, int attr, const char *str, BOOLEAN_P presel)
{
    struct webwin *w = getwin(id);
    struct wmenuitem *it;
    if (!w)
        return;
    if (w->nitems == w->maxitems) {
        int nm = w->maxitems ? w->maxitems * 2 : 32;
        struct wmenuitem *ni =
            (struct wmenuitem *) alloc(nm * sizeof(struct wmenuitem));
        if (w->nitems)
            memcpy(ni, w->items, w->nitems * sizeof(struct wmenuitem));
        free(w->items);
        w->items = ni;
        w->maxitems = nm;
    }
    it = &w->items[w->nitems++];
    it->id = *identifier;
    it->glyph = glyph;
    it->acc = ch;
    it->gacc = gch;
    it->attr = attr;
    it->str = dupstr(str);
    it->presel = presel;
}

