#define KQ_SIZE 512
static char keyq[KQ_SIZE];
static int kq_head, kq_tail;

static int
kq_empty(void)
{
    return kq_head == kq_tail;
}

static int
kq_pop(void)
{
    int c = (unsigned char) keyq[kq_head];
    kq_head = (kq_head + 1) % KQ_SIZE;
    return c;
}

static void
kq_push(int c)
{
    int nt = (kq_tail + 1) % KQ_SIZE;
    if (nt == kq_head)
        return; /* full, drop */
    keyq[kq_tail] = (char) c;
    kq_tail = nt;
}

static void
kq_clear(void)
{
    kq_head = kq_tail = 0;
}

static int
hexval(int c)
{
    if (c >= '0' && c <= '9')
        return c - '0';
    if (c >= 'a' && c <= 'f')
        return c - 'a' + 10;
    if (c >= 'A' && c <= 'F')
        return c - 'A' + 10;
    return -1;
}

/* decode hex in place, return length */
static int
unhex(char *s)
{
    int n = 0, h, l;
    char *p = s;
    while ((h = hexval(p[0])) >= 0 && (l = hexval(p[1])) >= 0) {
        s[n++] = (char) (h * 16 + l);
        p += 2;
    }
    s[n] = '\0';
    return n;
}

