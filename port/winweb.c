static char
web_yn_function(const char *query, const char *resp, CHAR_P def)
{
    int q;
    char rbuf[BUFSZ];

    Strcpy(rbuf, resp ? resp : "");
    /* only the part before an ESC is a real choice list */
    {
        char *e = index(rbuf, '\033');
        if (e)
            *e = '\0';
    }
    for (;;) {
        if (kq_empty()) {
            sync_all();
            fputs("{\"t\":\"yn\",\"q\":", out);
            jstr(query);
            fputs(",\"r\":", out);
            jstr(rbuf);
            fprintf(out, ",\"d\":%d", (int) (unsigned char) def);
            endmsg();
            while (kq_empty()) {
                int c = read_cmd();
                if (c == 'X')
                    kq_push('\033');
            }
        }
        q = kq_pop();
        if (!resp || !*rbuf)
            return (char) q;
        if (q == '\033') {
            if (index(rbuf, 'q'))
                return 'q';
            if (index(rbuf, 'n'))
                return 'n';
            return def;
        }
        if (q == ' ' || q == '\n' || q == '\r')
            return def;
        if (index(rbuf, q))
            return (char) q;
        q = lowc(q);
        if (index(rbuf, q))
            return (char) q;
        kq_clear();
    }
}

static void
web_getlin(const char *prompt, char *outbuf)
{
    int c;
    sync_all();
    kq_clear();
    fputs("{\"t\":\"line\",\"q\":", out);
    jstr(prompt);
    endmsg();
    for (;;) {
        c = read_cmd();
        if (c == 'X') {
            Strcpy(outbuf, "\033");
            return;
        }
        if (c == 'K') {
            int k = kq_pop();
            kq_clear();
            if (k == '\033') {
                Strcpy(outbuf, "\033");
                return;
            }
        }
        if (c == 'L')
            break;
    }
    unhex(inbuf + 1);
    (void) strncpy(outbuf, inbuf + 1, BUFSZ - 1);
    outbuf[BUFSZ - 1] = '\0';
}

static int
web_get_ext_cmd(void)
{
    int c, i;
    sync_all();
    kq_clear();
    fputs("{\"t\":\"ext\"", out);
    endmsg();
    for (;;) {
        c = read_cmd();
        if (c == 'X')
            return -1;
        if (c == 'K') {
            kq_clear();
            return -1;
        }
        if (c == 'E')
            break;
    }
    for (i = 0; extcmdlist[i].ef_txt; i++)
        if (!strcmpi(extcmdlist[i].ef_txt, inbuf + 1) && !web_rite(inbuf + 1))
            return i;
    pline("%s: unknown extended command.", inbuf + 1);
    return -1;
}

