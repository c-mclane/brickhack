    fprintf(out, "{\"t\":\"throw\",\"tile\":%d,\"fx\":%d,\"fy\":%d,\"tx\":%d,\"ty\":%d,\"mon\":0,\"by\":\"monster\",\"shot\":%d",
            web_mt_tile, web_mt_x, web_mt_y, x, y, web_mt_shot);
