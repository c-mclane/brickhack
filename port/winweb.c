/* King Skelly III and the Realm Daggers (tools/patch_engine.py
   WEB_HOOK_SKELLY). The king of the underworld climbed out of Gehennom with
   the three Realm Daggers and took the Castle. Together the daggers open a
   portal to any realm you've reached; apart, each has a power of its own. */

static const int realm_arts[3] = { ART_DAGGER_OF_CREATION, ART_DAGGER_OF_PROTECTION,
                                   ART_DAGGER_OF_DESTRUCTION };

/* 0..2: which Realm Dagger (Creation, Protection, Destruction); -1: none */
static int
web_realm_which(struct obj *o)
{
    int i;
    for (i = 0; o && i < 3; i++)
        if (o->oartifact == realm_arts[i])
            return i;
    return -1;
}

/* how many of the three a chain of objects holds */
static int
web_realm_count(struct obj *chain)
{
    int seen = 0, k;
    for (; chain; chain = chain->nobj)
        if ((k = web_realm_which(chain)) >= 0)
            seen |= 1 << k;
    return !!(seen & 1) + !!(seen & 2) + !!(seen & 4);
}

/* the client's id for an object's look: its tile, or for an artifact
   ART_TILE + its number (an artifact shares its base item's tile, but has a
   brick model of its own: tools/build_items.py lists them for the client,
   which falls back to the base item's look for one without); and for a
   variant with a look of its own, VARIANT_TILE + its number: water you know
   is holy (0) or unholy (1) (items.json "variant"); and armour the hero
   started with, START_TILE + its category x 10000 + its own tile (the client
   shows its figure's design's piece for that slot, or else as ever); and a
   corpse, CORPSE_TILE + whose (its monster's own tile: the client shows a
   brick of that monster's own model) */
#define ART_TILE 90000
#define VARIANT_TILE 92000
#define CORPSE_TILE 94000
#define START_TILE 100000   /* + its armour category (oc_armcat) x 10000 + its own tile: armour the hero started with */
static int tile_of(int glyph);
static int
web_obj_tile(struct obj *o, int glyph)
{
    if (Hallucination)
        return tile_of(glyph);
    if (o->oartifact)
        return ART_TILE + o->oartifact;
    if (o->otyp == CORPSE && o->corpsenm >= LOW_PM && o->corpsenm < NUMMONS)
        return CORPSE_TILE + tile_of(monnum_to_glyph(o->corpsenm));
    if (o->otyp == POT_WATER && o->bknown && (o->blessed || o->cursed))
        return VARIANT_TILE + (o->blessed ? 0 : 1);
    if (o->webstart && o->oclass == ARMOR_CLASS)   /* the design's own piece, in its slot */
        return START_TILE + objects[o->otyp].oc_armcat * 10000 + tile_of(glyph);
    return tile_of(glyph);
}

/* u_init.c: what more a character starts with than its role's own kit, from
   its figure's design (the server's BRICKHACK_KIT: "holy wafer:4,...", name
   and how many): the i-th one's object type, its quantity in *quan; 0 for one
   that names no object, -1 past the last */
int
web_kit_item(int i, int *quan)
{
    const char *p = getenv("BRICKHACK_KIT");
    char name[BUFSZ];
    int n, k;

    for (; p && *p && i > 0; i--)   /* to the i-th */
        if ((p = index(p, ',')) != 0)
            p++;
    if (!p || !*p)
        return -1;
    for (n = 0; p[n] && p[n] != ',' && p[n] != ':' && n < BUFSZ - 1; n++)
        name[n] = p[n];
    name[n] = 0;
    *quan = p[n] == ':' ? atoi(p + n + 1) : 1;
    if (*quan < 1) *quan = 1;
    if (*quan > 63) *quan = 63;   /* (a starting item's count: trobj trquan) */
    for (k = 1; k < NUM_OBJECTS; k++)
        if (OBJ_NAME(objects[k]) && !strcmpi(OBJ_NAME(objects[k]), name))
            return k;
    return 0;
}

