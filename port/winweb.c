int web_freeze_map = 0;

/* fired, not thrown: obj is ammunition and the weapon wielded (launcher) the one to shoot it: 1 a bow or a
   crossbow (an arrow, a bolt: loosed, flat and fast), 2 a sling (a stone, whirled and let fly); else 0 */
static int
web_fired(struct obj *obj, struct obj *launcher)
{
    if (!obj || !launcher || !is_ammo(obj) || !ammo_and_launcher(obj, launcher))
        return 0;
    return objects[launcher->otyp].oc_skill == P_SLING ? 2 : 1;
}

