{
    dlb *f = dlb_fopen(fname, "r");
    char line[BUFSZ];
    struct webwin tmp;

    if (!f) {
        if (complain)
            pline("Cannot open \"%s\".", fname);
        return;
    }
    memset(&tmp, 0, sizeof tmp);
    while (dlb_fgets(line, sizeof line, f)) {
        char *nl = index(line, '\n');
        if (nl)
            *nl = '\0';
        add_line(&tmp, 0, line);
    }
    (void) dlb_fclose(f);
    show_text(&tmp);
    win_reset(&tmp);
    free(tmp.lines);
}

