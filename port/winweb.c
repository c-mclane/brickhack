static int
web_select_menu(winid id, int how, MENU_ITEM_P **menu_list)
{
    struct webwin *w = getwin(id);
    int i, n = 0;
    char autoacc = 'a';

    *menu_list = 0;
    if (!w)
        return -1;
    if (!w->nitems && w->nlines) { /* text shown through a menu window */
        show_text(w);
        return 0;
    }
    sync_all();
    fputs("{\"t\":\"menu\",\"how\":", out);
    fprintf(out, "%d,\"prompt\":", how);
    jstr(w->prompt ? w->prompt : "");
    fputs(",\"items\":[", out);
    for (i = 0; i < w->nitems; i++) {
        struct wmenuitem *it = &w->items[i];
        boolean sel = it->id.a_void != 0;
        char acc = it->acc;
        if (sel && !acc && how != PICK_NONE && autoacc) {
            acc = autoacc;
            autoacc = autoacc == 'z' ? 'A' : autoacc == 'Z' ? 0 : autoacc + 1;
        }
        fprintf(out, "%s{\"i\":%d,\"sel\":%d,\"a\":%d,\"t\":%d,\"k\":", i ? "," : "",
                i, sel, it->attr, tile_of(it->glyph));
        {
            char k[2] = { acc, 0 };
            jstr(k);
        }
        fputs(",\"s\":", out);
        jstr(it->str);
        fprintf(out, ",\"pre\":%d}", it->presel);
    }
    fputc(']', out);
    endmsg();
    kq_clear();

    for (;;) {
        int c = read_cmd();
        if (c == 'X' || (c == 'K' && !kq_empty() && kq_pop() == '\033')) {
            kq_clear();
            return how == PICK_NONE ? 0 : -1;
        }
        if (c == 'K') {
            kq_clear();
            continue;
        }
        if (c == 'M')
            break;
    }
    if (how == PICK_NONE)
        return 0;
    {
        /* parse "M i:c i:c ..." */
        char *p = inbuf + 1;
        int idx, cnt, consumed, cap = 0;
        MENU_ITEM_P *res = 0;
        while (sscanf(p, " %d:%d%n", &idx, &cnt, &consumed) == 2) {
            p += consumed;
            if (idx < 0 || idx >= w->nitems || !w->items[idx].id.a_void)
                continue;
            if (n == cap) {
                int nc = cap ? cap * 2 : 8;
                MENU_ITEM_P *nr = (MENU_ITEM_P *) alloc(nc * sizeof *nr);
                if (n)
                    memcpy(nr, res, n * sizeof *nr);
                free(res);
                res = nr;
                cap = nc;
            }
            res[n].item = w->items[idx].id;
            res[n].count = cnt;
            n++;
        }
        *menu_list = res;
    }
    return n;
}

