#!/usr/bin/env python3
"""Convert NetHack's win/share/{monsters,objects,other}.txt tile sources into
a single PNG atlas (stdlib only).  Tile index order matches glyph2tile[] as
generated by util/tilemap: monsters, then objects, then other.

usage: tiles2png.py <nethack-src-dir> <out.png> <out.json>
"""
import json, re, struct, sys, zlib

COLS = 40
TS = 16

def parse(path):
    palette, tiles, cur, name = {}, [], None, None
    for line in open(path, encoding="latin-1"):
        line = line.rstrip("\n")
        m = re.match(r"^(\S) = \((\d+),\s*(\d+),\s*(\d+)\)", line)
        if m:
            palette[m.group(1)] = tuple(int(m.group(i)) for i in (2, 3, 4))
            continue
        m = re.match(r"^# tile \d+ \((.*)\)", line)
        if m:
            name = m.group(1).strip()
            continue
        if line == "{":
            cur = []
        elif line == "}":
            tiles.append((name, cur))
            cur = None
        elif cur is not None:
            cur.append(line.strip())
    out = []
    for name, rows in tiles:
        px = []
        for r in rows:
            for ch in r:
                rgb = palette[ch]
                # NetHack tiles use (71,108,108) as the transparent background
                a = 255  # keyed out in the shader for billboards
                px.append(rgb + (a,))
        out.append((name, px))
    return out

def write_png(path, w, h, rgba):
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw.extend(rgba[y * w * 4:(y + 1) * w * 4])
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    open(path, "wb").write(png)

def main():
    src, out_png, out_json = sys.argv[1:4]
    tiles = []
    for f in ("monsters", "objects", "other"):
        tiles += parse(f"{src}/win/share/{f}.txt")
    # free slots after the last tile for the player's custom skin and the
    # client's own block textures (see web/js/textures.js)
    rows = (len(tiles) + 64 + COLS - 1) // COLS
    w, h = COLS * TS, rows * TS
    img = bytearray(w * h * 4)
    for i, (_, px) in enumerate(tiles):
        tx, ty = (i % COLS) * TS, (i // COLS) * TS
        for j, p in enumerate(px):
            x, y = tx + j % TS, ty + j // TS
            o = (y * w + x) * 4
            img[o:o + 4] = bytes(p)
    write_png(out_png, w, h, img)
    json.dump({"cols": COLS, "rows": rows, "size": TS, "count": len(tiles),
               "names": [n for n, _ in tiles]}, open(out_json, "w"))
    print(f"{len(tiles)} tiles -> {w}x{h}")

main()
