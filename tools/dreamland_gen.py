#!/usr/bin/env python3
"""Generate Ascend's level (the "dreamland" option, level dreamlnd): a blank
baseplate. One open, lit field of floor, nothing on it: no monsters, no
objects, no stairs. You start in the middle of it.

  <des>   SLASH'EM special level
  <.h>    (optional) for the engine: DREAM_LEVELS, how many levels of the
          first dungeon are Ascend's own (1)

usage: dreamland_gen.py <out.des> [<out.h>]
"""
import sys

W, H = 118, 62  # map size (SLASH'EM MAP_X_LIM/MAP_Y_LIM)
START = (W // 2, H // 2)  # where you start: the middle of the plate

des = [
    "# BrickHack Ascend: a blank baseplate (generated by tools/dreamland_gen.py)",
    'MAZE:"dreamlnd",\' \'',
    "GEOMETRY:center,center",
    "MAP",
    *("." * W for _ in range(H)),
    "ENDMAP",
    f"REGION:(0,0,{W - 1},{H - 1}),lit,\"ordinary\"",
    f"NON_DIGGABLE:(0,0,{W - 1},{H - 1})",
    # level 1 has no up stairs of its own: the dungeon's exit (where you
    # start) is the branch, so pin it to the middle of the plate
    f"BRANCH:({START[0]},{START[1]},{START[0]},{START[1]}),(0,0,0,0)",
]
open(sys.argv[1], "w").write("\n".join(des) + "\n")
if len(sys.argv) > 2:
    open(sys.argv[2], "w").write(
        "/* generated by tools/dreamland_gen.py */\n"
        "/* how many levels of the first dungeon are Ascend's own */\n"
        "#define DREAM_LEVELS 1\n")
print(f"ascend: a blank {W}x{H} baseplate")
