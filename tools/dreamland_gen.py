#!/usr/bin/env python3
"""Generate Ascend's level (the "dreamland" option, level dreamlnd): the meadow
before the golden castle. A wide, lit meadow, bordered all round by woods (a
band of trees, ragged at its inner edge), beyond them solid stone that can't be
dug (the client draws it as haze); in the meadow's north the castle (the
yellow castle of 1978, in chrome gold: items.json "_castle375"), eight squares
square: its walls a ring of wall the client doesn't draw (it stands the model
there instead), its gate open in the middle of its south wall, the drawbridge
down before it; you start on the meadow before the drawbridge. The king's
enemies are out on the meadow (orcs, goblins, kobolds, jackals...), and more
come out of the woods as they fall (winweb.c web_dream_tick).

  <des>   SLASH'EM special level
  <.h>    (optional) for the engine: DREAM_LEVELS, how many levels of the
          first dungeon are Ascend's own (1), and where the castle stands
  <json>  (optional) for the client: where the castle stands
          (web/assets/brick/ascend.json)

usage: dreamland_gen.py <out.des> [<out.h> [<out.json>]]
"""
import json, random, sys

W, H = 118, 62  # map size (SLASH'EM MAP_X_LIM/MAP_Y_LIM)
MW, MH = 56, 30  # the meadow: this many squares each way, in the middle
WOODS = 4  # the woods round it: this deep (and a ragged edge a square further in)
MX0, MY0 = (W - MW) // 2, (H - MH) // 2
CASTLE = 8  # the castle: 8 squares square (its 32x32 studs: four to a square)
CX0, CY0 = MX0 + (MW - CASTLE) // 2, MY0 + 4  # (in the meadow's north, its middle)
GATE = (CX0 + 3, CX0 + 4)  # (its gate: the middle two squares of its south wall)
START = (CX0 + 4, CY0 + CASTLE + 4)  # where you start: on the meadow, before the drawbridge
OFF = 1  # (the map's squares to the level's: a map the level's whole size, centred, starts at (1, 1): sp_lev.c xstart, ystart)

rng = random.Random(375)
grid = [[" "] * W for _ in range(H)]
for y in range(MY0 - WOODS, MY0 + MH + WOODS):
    for x in range(MX0 - WOODS, MX0 + MW + WOODS):
        inside = MX0 <= x < MX0 + MW and MY0 <= y < MY0 + MH
        grid[y][x] = "." if inside else "T"
for y in range(MY0, MY0 + MH):   # (the woods' ragged edge: a tree here and there a square in, now and then two)
    for x in range(MX0, MX0 + MW):
        edge = min(x - MX0, MX0 + MW - 1 - x, y - MY0, MY0 + MH - 1 - y)
        if (edge == 0 and rng.random() < 0.45) or (edge == 1 and rng.random() < 0.12):
            grid[y][x] = "T"
for y in range(CY0 - 1, CY0 + CASTLE + 6):   # (clear about the castle, and the way to its gate)
    for x in range(CX0 - 1, CX0 + CASTLE + 1):
        if grid[y][x] == "T": grid[y][x] = "."
for y in range(CY0, CY0 + CASTLE):   # the castle: a ring of wall, the courtyard inside, the gate in the south wall
    for x in range(CX0, CX0 + CASTLE):
        ring = y in (CY0, CY0 + CASTLE - 1) or x in (CX0, CX0 + CASTLE - 1)
        grid[y][x] = ("-" if y in (CY0, CY0 + CASTLE - 1) else "|") if ring else "."
for x in GATE:
    grid[CY0 + CASTLE - 1][x] = "."
for x in GATE:   # (the two pillars inside, either side of the great door under the tall tower)
    grid[CY0 + 1][x] = "|"

# the king's enemies, out on the meadow (more come out of the woods: web_dream_tick)
FOES = [("o", "hill orc"), ("o", "hill orc"), ("o", "goblin"), ("o", "goblin"), ("o", "hobgoblin"), ("k", "kobold"),
        ("k", "large kobold"), ("d", "jackal"), ("d", "jackal"), ("o", "Mordor orc")]
spots = []
while len(spots) < len(FOES):
    x, y = rng.randrange(MX0 + 2, MX0 + MW - 2), rng.randrange(MY0 + 2, MY0 + MH - 2)
    if grid[y][x] == "." and abs(x - START[0]) + abs(y - START[1]) > 12 and not (CX0 - 1 <= x <= CX0 + CASTLE and CY0 - 1 <= y <= CY0 + CASTLE + 5):
        spots.append((x, y))

des = [
    "# BrickHack Ascend: the meadow before the golden castle (generated by tools/dreamland_gen.py)",
    'MAZE:"dreamlnd",\' \'',
    "GEOMETRY:center,center",
    "MAP",
    *("".join(r) for r in grid),
    "ENDMAP",
    f"REGION:(0,0,{W - 1},{H - 1}),lit,\"ordinary\"",
    f"NON_DIGGABLE:(0,0,{W - 1},{H - 1})",
    f"NON_PASSWALL:({CX0},{CY0},{CX0 + CASTLE - 1},{CY0 + CASTLE - 1})",
    # level 1 has no up stairs of its own: the dungeon's exit (where you start) is the branch, before the drawbridge
    f"BRANCH:({START[0]},{START[1]},{START[0]},{START[1]}),(0,0,0,0)",
    *(f"MONSTER:'{c}',\"{n}\",({x},{y}),hostile" for (c, n), (x, y) in zip(FOES, spots)),
]
open(sys.argv[1], "w").write("\n".join(des) + "\n")
if len(sys.argv) > 2:
    open(sys.argv[2], "w").write(
        "/* generated by tools/dreamland_gen.py */\n"
        "/* how many levels of the first dungeon are Ascend's own */\n"
        "#define DREAM_LEVELS 1\n"
        "/* the castle on Ascend's meadow: its north-west corner and size, in the level map's squares (winweb.c:\n"
        "   enemies come out of the woods, never in it) */\n"
        f"#define DREAM_CASTLE_X {CX0 + OFF}\n#define DREAM_CASTLE_Y {CY0 + OFF}\n#define DREAM_CASTLE_N {CASTLE}\n")
if len(sys.argv) > 3:
    json.dump({"castle": [CX0 + OFF, CY0 + OFF, CX0 + OFF + CASTLE - 1, CY0 + OFF + CASTLE - 1], "item": "_castle375"}, open(sys.argv[3], "w"))
    open(sys.argv[3], "a").write("\n")
print(f"ascend: a {MW}x{MH} meadow in woods, the castle at ({CX0},{CY0}), you before its gate at {START}")
